// dcArms stands the five arms up over the shared fixture, exactly as the arc-R1
// table does — the single-process pipeline, the same under a 512 KiB budget,
// and the stage DAG broadcast, shuffled and morselled.
func dcArms(t *testing.T, ctx context.Context) []r1Arm {
	t.Helper()
	return r1Arms(t, ctx)
}

func TestArcDCADecorrelatedBodyKeepsEveryOuterReferenceOnEveryArm(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: five arms over a 776-cell table")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Minute)
	t.Cleanup(cancel)
	arms := dcArms(t, ctx)
	derived := r1Set(dcRefusedCorrelatedDerived)
	bare := r1Set(dcRefusedBareOuterRef)
	outerAgg := r1Set(dcRefusedOuterAggregate)

	seen := make(map[string]bool, len(dcPostgresRowSets))
	for _, tc := range dcCases() {
		want, ok := dcPostgresRowSets[tc.name]
		if !ok {
			t.Fatalf("%s: no PostgreSQL row set recorded — the table and the "+
				"measurement have diverged", tc.name)
		}
		seen[tc.name] = true
		t.Run(tc.name, func(t *testing.T) {
			for _, arm := range arms {
				got := arm.run(tc.sql)
				refusal := ""
				switch {
				case derived[tc.name]:
					refusal = dcCorrelatedDerivedRefusal
				case bare[tc.name]:
					refusal = dcBareOuterRefRefusal
				case outerAgg[tc.name]:
					refusal = dcOuterAggregateRefusal
				}
				if refusal != "" {
					// A PIN THAT STARTS AGREEING FAILS. When the boundary
					// closes, the cell is asserted against PostgreSQL — which
					// is already recorded above — and the pin is deleted.
					if !strings.Contains(got, refusal) {
						t.Errorf("%s\n  arm  %s\n  got  %s\n  the pinned refusal (%q) is gone: "+
							"assert PostgreSQL's row set %s and delete this cell's pin",
							tc.sql, arm.name, got, refusal, want)
					}
					continue
				}
				if got != want {
					t.Errorf("%s\n  arm  %s\n  got  %s\n  want %s (PostgreSQL 17.11)",
						tc.sql, arm.name, got, want)
				}
			}
		})
	}
	for name := range dcPostgresRowSets {
		if !seen[name] {
			t.Errorf("%s: a PostgreSQL row set is recorded for a cell the table "+
				"no longer writes", name)
		}
	}
}
