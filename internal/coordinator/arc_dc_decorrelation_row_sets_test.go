// A DECORRELATED SUBQUERY KEEPS EVERY OUTER REFERENCE, WHEREVER IN ITS BODY
// IT IS WRITTEN — #1232, #1104, on FIVE ARMS.
//
// The corpus is arc_dc_decorrelation_cases_test.go: {IN, NOT IN, = ANY,
// <> ALL, EXISTS, NOT EXISTS, a scalar subquery in WHERE, a scalar subquery in
// the SELECT list} × {the fifty places an outer reference can sit in a body —
// its WHERE with an inner column, its WHERE naming only the outer row, a JOIN's
// ON, a LEFT/RIGHT JOIN's ON, a comma join's WHERE, the HAVING, the SELECT
// list, a nested derived table, a nested subquery, two references in two
// places} × {equality, inequality, a function over the outer column, a CAST,
// IS DISTINCT FROM, a NULL-yielding predicate, an outer row with NULL in the
// referenced column, an empty inner, duplicate inner keys} × {an enclosing
// query that is ONE relation, and one that is a JOIN whose two arms both
// publish `id`}.
//
// Every want is live PostgreSQL 17.11 (postgres:17-alpine, --locale=C, the
// dc_out / dc_in / dc_side / dc_nul rows arc_dc_decorrelation_fixture_test.go
// writes, plus lat_ord / lat_item for the two issues' own shapes), measured at
// 6b9c7acf before a line changed and re-measured at the tip. What the fixes
// moved, in cells of this table, on the single arm:
//
//	#1232  the body's JOIN ON was never read. The ON is where the outer
//	       reference of `o.id IN (SELECT b.order_id FROM lat_item b JOIN
//	       lat_item c ON c.id = b.id AND o.total > b.amount)` lives, so the
//	       body's join was built with `o.total` in a condition whose scope
//	       does not contain `o`: ZERO rows for PostgreSQL's two, silently.
//	       109 wrong cells at base; an INNER join's ON conjunct is now a
//	       WHERE conjunct and an outer join's ON declines the rewrite.
//	#1104  a condition naming ONLY the outer row was added to the build
//	       side's filter with its qualifier STRIPPED (IN) or dropped outright
//	       (EXISTS). It now gates the OUTER rows, which is what PostgreSQL
//	       does with it, and the negated operators — for which that is not a
//	       conjunction — decline and re-run per outer row.
//
// 193 of this table's 776 cells changed. None of the other 583 moved, and no
// cell that agreed with PostgreSQL at base is refused at the tip.
//
// The three PINS below are boundaries, not answers, and each names what
// closes it. A pin that starts agreeing FAILS: PostgreSQL's row set for the
// cell is already recorded above it.
const (
	// An outer reference inside a DERIVED TABLE in the body's FROM. This
	// engine plans a derived table's body as its own query block, where the
	// enclosing relation names nothing — the standing 0A000-class gap
	// (#614/#1045, ADR-0021 §1p), refused with its two workarounds named.
	// Pre-existing at 6b9c7acf on all five arms.
	dcCorrelatedDerivedRefusal = "from an enclosing query is not supported"
	// An outer reference written WITHOUT a qualifier. The logical classifier
	// has no catalog for the body's own relations, so it cannot tell the
	// enclosing `total` from an inner column of the same name — and TPC-H
	// Q02's official spelling writes every correlated key unqualified, with
	// both names in the enclosing map, so reading an unqualified name as
	// outer would change Q02's row set. The unqualified spelling therefore
	// keeps the disposition it had: it goes to the build side, where the
	// column is absent and the failure is LOUD. Closing it is a catalog at
	// the classifier, not a spelling rule (ADR-0021 §1r). Pre-existing at
	// 6b9c7acf.
	dcBareOuterRefRefusal = "does not exist in the input schema"
	// An aggregate inside a subquery whose ARGUMENT names only the enclosing
	// query. PostgreSQL puts such an aggregate at the ENCLOSING query's
	// level and then raises 42803 for these statements; this engine refuses
	// by name (ADR-0021 §1g). Both refuse, which is the assertion.
	dcOuterAggregateRefusal = "names only the enclosing query"
)

