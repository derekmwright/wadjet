package wadjet

// ntPgCell is one measured PostgreSQL 17.11 answer: the literal, the text the
// server canonicalizes it to, and the SQLSTATE when it refuses. Exactly one of
// value/state is set.
//
// These three tables ARE the grammar this engine claims to implement. They are
// generated from a live server rather than written by hand, and they carry
// PostgreSQL's REJECTED forms as well as its accepted ones — a table built
// from the spellings an issue happened to name can agree with the code while
// the grammar is wrong one character over, which is how the round-1 gate
// passed with three grammar defects present (review NT, B1/B2/B3).
type ntPgCell struct {
	form  string
	value string
	state string
}

